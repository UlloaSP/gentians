"""Deterministic constraint-learning task with 1,149,016 legal clauses."""

import random
import argparse
from math import comb
from pathlib import Path

from gentians.language.lexer import lex


def clause_count(features: int = 32, max_body: int = 6) -> int:
    return sum(comb(features, width) for width in range(1, min(max_body, features) + 1))


def task_text(features: int = 32) -> str:
    if features < 2:
        raise ValueError("at least two features are required")
    rng = random.Random(20260908)
    pairs = min(6, features // 2)

    def valid(mask: int) -> bool:
        return not any(mask & (3 << (2 * pair)) == 3 << (2 * pair)
                       for pair in range(pairs))

    # Singleton positives prevent rejecting a feature without its partner.
    # The all-true negative ensures all feature conjunctions can co-occur.
    positives = {0, *(1 << feature for feature in range(features))}
    negatives = {(1 << features) - 1}
    for _ in range(256):
        mask = rng.getrandbits(features)
        target = positives if valid(mask) else negatives
        limit = features + 25 if valid(mask) else 25
        if len(target) < limit:
            target.add(mask)
    worlds = [(mask, True) for mask in sorted(positives)]
    worlds += [(mask, False) for mask in sorted(negatives)]
    lines = [
        "% Generated by uv run python -m benchmarks.synthetic_million",
        f"% Legal clauses: {clause_count(features):,}; up to six per hypothesis.",
        "#maxv(1).", "#maxbl(6).", "#maxhl(0).", "#maxpl(6).",
        f"world(0..{len(worlds) - 1}).",
        "1 { active(X) : world(X) } 1.",
    ]
    for feature in range(features):
        lines.append(f"f{feature}(X) :- active(X), has{feature}(X).")
        lines.extend(f"has{feature}({world})." for world, (mask, _) in enumerate(worlds)
                     if mask & (1 << feature))
        lines.append(f"#modeb(1,f{feature}(var(world,output))).")
    lines.extend(f"#{'pos' if positive else 'neg'}({{active({world})}}, {{}})."
                 for world, (_, positive) in enumerate(worlds))
    return "\n".join(lines) + "\n"


def scaling_task_text(max_body: int) -> str:
    """Vary body length only; keep all features, examples and the solution fixed."""
    if not 2 <= max_body <= 6:
        raise ValueError("max_body must be between 2 and 6")
    return task_text().replace("#maxbl(6).", f"#maxbl({max_body}).").replace(
        "Legal clauses: 1,149,016", f"Legal clauses: {clause_count(max_body=max_body):,}"
    )


def task_parts(source: str) -> dict[str, str]:
    parts: dict[str, list[str]] = {"bk.lp": [], "exs.lp": [], "bias.lp": []}
    for statement in lex(source):
        directive = statement.directive
        name = (
            "exs.lp" if directive in ("#pos", "#neg") else
            "bias.lp" if directive and directive.startswith(("#max", "#mode")) else
            "bk.lp"
        )
        parts[name].append(statement.text)
    return {name: "\n".join(statements) + "\n" for name, statements in parts.items()}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sweep", action="store_true", help="Write fixed-example scaling tasks.")
    if parser.parse_args().sweep:
        directory = Path(__file__).resolve().parents[1] / ".benchmarks/experiments/incremental-crossover/tasks"
        directory.mkdir(parents=True, exist_ok=True)
        for max_body in range(2, 7):
            path = directory / f"body{max_body}.txt"
            path.write_text(scaling_task_text(max_body), encoding="utf-8")
            print(f"{path}: {clause_count(max_body=max_body):,} legal clauses")
    else:
        directory = Path(__file__).with_name("gentians") / "synthetic_million"
        directory.mkdir(exist_ok=True)
        for name, content in task_parts(task_text()).items():
            (directory / name).write_text(content, encoding="utf-8", newline="\n")
        print(f"{directory}: {clause_count():,} legal clauses")
