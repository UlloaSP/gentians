import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from benchmarks.catalog import CASES  # noqa: E402
from gentians.clauses import generate_clause_space  # noqa: E402
from gentians.gentians import task_from_arguments  # noqa: E402


DEFAULT_OUTPUT = (
    Path(".benchmarks")
    / "experiments"
    / "ilasp-5queens-explicit"
    / "5queens-explicit.las"
)
ILASP_BASE = Path("benchmarks/ilasp/5queens.las")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Export Gentians' 5-queens ClauseSpace as explicit ILASP rules."
    )
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    arguments = CASES["5queens"]
    task = task_from_arguments(arguments)
    clause_space = generate_clause_space(task, arguments)

    base_lines = ILASP_BASE.read_text(encoding="utf-8").splitlines()
    task_lines = [
        line
        for line in base_lines
        if not line.startswith("% ILASP translation")
        and not line.startswith("% The hypothesis space")
        and not line.startswith("#maxv")
        and not line.startswith("#mode")
    ]
    explicit_rules = [
        f"{entry.body_literals} ~ {entry.text}" for entry in clause_space.entries
    ]
    output = "\n".join(
        [
            "% 5-queens with the Gentians ClauseSpace supplied explicitly to ILASP.",
            "% Each entry has the ILASP form: length ~ clause.",
            *task_lines,
            "% Explicit hypothesis space generated by Gentians.",
            *explicit_rules,
            "",
        ]
    )

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(output.encode("utf-8"))
    print(f"{len(clause_space)} clauses -> {args.output}")


if __name__ == "__main__":
    main()
