"""Export complete Gentians clause spaces for tasks with body aggregate modes."""

import argparse
import hashlib
import sys
from pathlib import Path

from clingo import ast

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from benchmarks.catalog import CASES, arguments_for  # noqa: E402
from gentians.clauses import generate_clause_space  # noqa: E402
from gentians.clauses.clause_space import ClauseSpace  # noqa: E402
from gentians.gentians import task_from_arguments  # noqa: E402
from gentians.language.lexer import lex  # noqa: E402
from gentians.language.asp import parse_program  # noqa: E402
from gentians.language.ir.aggregate_literal import AggregateLiteral  # noqa: E402
from gentians.language.ir.inductive_task import InductiveTask  # noqa: E402


def has_body_aggregates(task: InductiveTask) -> bool:
    return any(isinstance(mode.literal, AggregateLiteral) for mode in task.language_bias_body)


def background_statement(text: str) -> str:
    """ILASP needs explicit bounds even on an unconditional singleton choice."""
    statement = parse_program(text)[0]
    if statement.ast_type != ast.ASTType.Rule:
        return text
    head = statement.head
    if head.ast_type != ast.ASTType.Aggregate or head.left_guard or head.right_guard:
        return text
    if len(head.elements) != 1 or head.elements[0].condition:
        raise ValueError("Unbounded conditional/multiple choice needs explicit ILASP translation")
    body = " :- " + ", ".join(map(str, statement.body)) if statement.body else ""
    return f"0 {{{head.elements[0]}}} 1{body}."


def render_task(task: InductiveTask, space: ClauseSpace, source: Path) -> str:
    if not has_body_aggregates(task):
        raise ValueError(f"{source.name}: explicit export is only for body aggregate tasks")
    lines = [
        f"% Generated by benchmarks/export_ilasp_aggregates.py from {source.name}.",
        f"% Source SHA256 (UTF-8, LF): {hashlib.sha256(source.read_text(encoding='utf-8').encode('utf-8')).hexdigest()}",
        "% Complete canonical ClauseSpace; no selection by coverage or target solution.",
        "% Cost = top-level body literals + head atom (zero for constraints).",
        "% Generation is offline and is not included in ILASP run times.",
        "",
        *(background_statement(statement.text) for statement in lex(source.read_text(encoding="utf-8"))
          if statement.directive is None),
        "",
    ]
    for example in (*task.positive_examples, *task.negative_examples):
        kind = "pos" if example.positive else "neg"
        fields = [f"{{{example.included_text}}}", f"{{{example.excluded_text}}}"]
        if example.context:
            fields.append("{" + example.context_text + "}")
        lines.append(f"#{kind}({', '.join(fields)}).")
    lines.extend(("", f"% Explicit hypothesis space: {len(space)} candidate clauses."))
    for clause in space.entries:
        cost = clause.body_literals + bool(clause.heads)
        lines.append(f"{cost} ~ {clause.text}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--datasets", nargs="+", choices=sorted(CASES))
    parser.add_argument("--out-dir", type=Path, default=REPO_ROOT / "benchmarks" / "ilasp")
    args = parser.parse_args()
    for dataset in args.datasets or sorted(CASES):
        arguments = arguments_for(dataset)
        task = task_from_arguments(arguments)
        if not has_body_aggregates(task):
            if args.datasets:
                raise SystemExit(f"{dataset}: no body aggregate modes")
            continue
        print(f"{dataset}: generating complete ClauseSpace...", flush=True)
        space = generate_clause_space(task, arguments)
        content = render_task(task, space, Path(arguments.filename))
        args.out_dir.mkdir(parents=True, exist_ok=True)
        (args.out_dir / f"{dataset}.las").write_text(content, encoding="utf-8", newline="\n")
        print(f"{dataset}: {len(space)} clauses exported", flush=True)


if __name__ == "__main__":
    main()
